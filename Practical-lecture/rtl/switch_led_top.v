`timescale 1ns/1ps
module switch_led_top(
    input wire CLK100MHZ,
    input wire CPU_RESETN,
    input wire [15:0] SW,
    output reg [15:0] LED = 16'h0000
);
    // Asynchronous assertion, synchronous release; also reset after configuration.
    (* ASYNC_REG = "TRUE" *) reg [3:0] reset_pipe = 4'b1111;
    always @(posedge CLK100MHZ or negedge CPU_RESETN)
        if (!CPU_RESETN) reset_pipe <= 4'b1111;
        else reset_pipe <= {reset_pipe[2:0], 1'b0};
    wire reset = reset_pipe[3];

    (* ASYNC_REG = "TRUE" *) reg [15:0] sw_meta = 0, sw_sync = 0;
    always @(posedge CLK100MHZ) begin
        sw_meta <= SW;
        sw_sync <= sw_meta;
    end

    wire [11:0] address;
    wire [17:0] instruction;
    wire bram_enable, write_strobe;
    wire [7:0] port_id, out_port;
    reg [7:0] in_port;
    always @* begin
        case (port_id)
            8'h00: in_port = sw_sync[7:0];
            8'h01: in_port = sw_sync[15:8];
            default: in_port = 8'h00;
        endcase
    end

    kcpsm6 #(.interrupt_vector(12'h3FF), .scratch_pad_memory_size(64), .hwbuild(8'h00)) cpu (
        .address(address), .instruction(instruction), .bram_enable(bram_enable),
        .in_port(in_port), .out_port(out_port), .port_id(port_id),
        .write_strobe(write_strobe), .k_write_strobe(), .read_strobe(),
        .interrupt(1'b0), .interrupt_ack(), .sleep(1'b0),
        .reset(reset), .clk(CLK100MHZ)
    );
    // Actual 1024 x 18-bit program memory, generated by the KCPSM6 assembler.
    switch_led program_rom (
        .address(address), .instruction(instruction),
        .enable(bram_enable), .clk(CLK100MHZ)
    );
    always @(posedge CLK100MHZ) begin
        if (reset) LED <= 16'h0000;
        else if (write_strobe) begin
            case (port_id)
                8'h00: LED[7:0] <= out_port;
                8'h01: LED[15:8] <= out_port;
            endcase
        end
    end
endmodule
